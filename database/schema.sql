-- AQUASENSE DATABASE

-- 1. AREAS

CREATE TABLE IF NOT EXISTS public.areas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_name TEXT UNIQUE NOT NULL,
    water_availability NUMERIC(5,2),
    groundwater_level NUMERIC(6,2),
    shortage_risk NUMERIC(5,2),
    created_at TIMESTAMPTZ DEFAULT NOW()
);


-- 2. WATER READINGS

CREATE TABLE IF NOT EXISTS public.water_readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_id BIGINT REFERENCES public.areas(id),
    water_usage NUMERIC(12,2) NOT NULL,
    flow_rate NUMERIC(10,2),
    pressure NUMERIC(10,2),
    reading_date TIMESTAMPTZ DEFAULT NOW()
);


-- 3. LEAKAGE ALERTS

CREATE TABLE IF NOT EXISTS public.leakage_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_id BIGINT REFERENCES public.areas(id),
    location TEXT NOT NULL,
    severity TEXT NOT NULL,
    flow_rate NUMERIC(10,2),
    expected_flow NUMERIC(10,2),
    status TEXT DEFAULT 'Open',
    created_at TIMESTAMPTZ DEFAULT NOW()
);


-- 4. WATER ISSUES

CREATE TABLE IF NOT EXISTS public.water_issues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_id BIGINT REFERENCES public.areas(id),
    issue_type TEXT NOT NULL,
    description TEXT,
    solution TEXT,
    status TEXT DEFAULT 'Reported',
    created_at TIMESTAMPTZ DEFAULT NOW()
);


-- 5. WATER PREDICTIONS

CREATE TABLE IF NOT EXISTS public.water_predictions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_id BIGINT REFERENCES public.areas(id),
    shortage_risk NUMERIC(5,2),
    forecast_days INTEGER,
    prediction_status TEXT,
    predicted_at TIMESTAMPTZ DEFAULT NOW()
);


